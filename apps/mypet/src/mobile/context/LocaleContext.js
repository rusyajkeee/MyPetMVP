const LocaleCtx = createContext({ locale: 'en', setLocale: () => {} });

export const LOCALES = [
  { code: 'en', label: 'EN', flag: '🇬🇧' },
  { code: 'ru', label: 'RU', flag: '🇷🇺' },
  { code: 'kz', label: 'ҚЗ', flag: '🇰🇿' },
];

export function LocaleProvider({ children }) {
  const [locale, setLocaleState] = useState('en');

  useEffect(() => {
    AsyncStorage.getItem('@mypet_locale')
      .then((v) => { if (v && STRINGS[v]) setLocaleState(v); })
      .catch(() => {});
  }, []);

  const setLocale = useCallback((code) => {
    if (!STRINGS[code]) return;
    setLocaleState(code);
    AsyncStorage.setItem('@mypet_locale', code).catch(() => {});
  }, []);

  return (
    <LocaleCtx.Provider value={{ locale, setLocale }}>
      {children}
    </LocaleCtx.Provider>
  );
}

export function useLocale() {
  return useContext(LocaleCtx);
}

export function useT() {
  const { locale } = useLocale();
  return (key) => STRINGS[locale]?.[key] ?? STRINGS.en[key] ?? key;
}
